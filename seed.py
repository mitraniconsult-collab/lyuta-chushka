FILLER = (
    "<p>{lead}</p>"
    "<p>Това е демонстрационен абзац, който показва как изглежда основният текст на статията: ширина на колоната, "
    "междуредие и четливост на мобилен екран. Истинските материали ще се пишат по проверени факти от първоизточници.</p>"
    "<h2>Какво следва</h2>"
    "<p>Подзаглавията помагат на читателя да скролира и на търсачките да разберат структурата на текста. "
    "Всеки материал има посочени източници най-отдолу.</p>"
    "<blockquote>Така изглежда цитат във визията на сайта.</blockquote>"
    "<p>Краят на демонстрационния текст.</p>"
)


def main():
    Base.metadata.create_all(engine)
    db = SessionLocal()
    if "--clear-demo" in sys.argv:
        n = db.query(Article).filter_by(is_demo=True).delete()
        db.commit()
        print(f"Изтрити демо материали: {n}")
        return
    if db.query(Article).filter_by(is_demo=True).count():
        print("Демо данните вече са заредени.")
        return
    now = utcnow()
    for i, (cat, title, summary, lead) in enumerate(DEMO):
        db.add(Article(
            slug=unique_slug(db, title), title=title, summary=summary, body=FILLER.format(lead=lead),
            category=cat, sources="Пример за източник | https://example.com",
            ai_generated=True, human_reviewed=(i % 2 == 0), risk_level="low",
            status="published", is_demo=True, views=100 - i * 13,
            published_at=now - dt.timedelta(hours=i * 5),
        ))
        db.commit()
    db.add(Article(
        slug=unique_slug(db, "Демо чакаща статия"), title="Демо: Материал, който чака одобрение",
        summary="Пример за статия във висок риск, задържана от филтъра.",
        body="<p>Демо.</p>", category="politika", sources="", ai_generated=True,
        risk_level="high", risk_reasons="няма посочен източник", status="pending", is_demo=True,
    ))
    db.commit()
    print("Демо данните са заредени.")


if __name__ == "__main__":
    main()
